CREATE TABLE IF NOT EXISTS prometheus_chat_conversations (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title VARCHAR(120) NOT NULL DEFAULT 'Nova conversa',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_prometheus_chat_conversation_owner UNIQUE (id, user_id)
);

CREATE INDEX IF NOT EXISTS idx_prometheus_chat_conversations_owner_updated
  ON prometheus_chat_conversations (user_id, updated_at DESC);

CREATE TABLE IF NOT EXISTS prometheus_chat_messages (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  sequence BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL UNIQUE,
  conversation_id UUID NOT NULL,
  user_id UUID NOT NULL,
  role VARCHAR(12) NOT NULL CHECK (role IN ('user', 'assistant', 'system')),
  content TEXT NOT NULL CHECK (length(content) <= 40000),
  status VARCHAR(16) NOT NULL DEFAULT 'complete',
  provider VARCHAR(40),
  model VARCHAR(100),
  provider_task_id VARCHAR(180),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT ck_prometheus_chat_message_status
    CHECK (status IN ('running', 'complete', 'waiting', 'failed')),
  CONSTRAINT fk_prometheus_chat_message_owner
    FOREIGN KEY (conversation_id, user_id)
    REFERENCES prometheus_chat_conversations (id, user_id)
    ON DELETE CASCADE
);

ALTER TABLE prometheus_chat_messages
  ADD COLUMN IF NOT EXISTS sequence BIGINT GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE prometheus_chat_messages
  ADD COLUMN IF NOT EXISTS status VARCHAR(16) NOT NULL DEFAULT 'complete';
ALTER TABLE prometheus_chat_messages
  ADD COLUMN IF NOT EXISTS provider_task_id VARCHAR(180);

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
     WHERE conname = 'ck_prometheus_chat_message_status'
       AND conrelid = 'prometheus_chat_messages'::regclass
  ) THEN
    ALTER TABLE prometheus_chat_messages
      ADD CONSTRAINT ck_prometheus_chat_message_status
      CHECK (status IN ('running', 'complete', 'waiting', 'failed'));
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_prometheus_chat_messages_conversation_sequence
  ON prometheus_chat_messages (conversation_id, user_id, sequence);

CREATE TABLE IF NOT EXISTS prometheus_chat_rate_buckets (
  user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  route_key VARCHAR(60) NOT NULL,
  window_start_epoch BIGINT NOT NULL,
  request_count INTEGER NOT NULL DEFAULT 0 CHECK (request_count >= 0),
  PRIMARY KEY (user_id, route_key, window_start_epoch)
);

CREATE INDEX IF NOT EXISTS idx_prometheus_chat_rate_buckets_window
  ON prometheus_chat_rate_buckets (window_start_epoch);
